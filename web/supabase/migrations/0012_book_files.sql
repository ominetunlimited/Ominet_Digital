-- Books get real commerce/publishing fields and attached files.
--
-- book_files holds the actual PDF/EPUB/MOBI/DOCX. The files themselves live
-- in a PRIVATE storage bucket ("book-files") and this table has NO public
-- policy: a paid file must never be reachable by a guessable URL. Delivery
-- (signed, expiring links after payment) is a later stage; until then files
-- can only be uploaded, analysed and test-downloaded by staff.
--
-- The bucket is created by a script with the service role rather than SQL
-- (bucket inserts via the SQL Editor have not persisted reliably here).

alter table books add column if not exists author text;
alter table books add column if not exists publication_date date;
alter table books add column if not exists category text;
alter table books add column if not exists tags text[] not null default '{}';
alter table books add column if not exists price_cents integer;
alter table books add column if not exists currency text not null default 'NGN';
-- external_only: sold/linked elsewhere (default, what every existing book is)
-- free_download: price 0, direct download from this site
-- direct_sale:   paid, sold here through Paystack
alter table books add column if not exists sales_mode text not null default 'external_only';
alter table books add column if not exists page_count integer;
alter table books add column if not exists page_count_source text; -- pdf | docx | epub | manual
alter table books add column if not exists og_image_url text;

alter table books drop constraint if exists books_sales_mode_check;
alter table books add constraint books_sales_mode_check check (sales_mode in ('external_only', 'free_download', 'direct_sale'));
alter table books drop constraint if exists books_price_matches_mode;
alter table books add constraint books_price_matches_mode check (
  (sales_mode = 'direct_sale' and price_cents is not null and price_cents > 0)
  or (sales_mode = 'free_download' and coalesce(price_cents, 0) = 0)
  or sales_mode = 'external_only'
);

create type book_file_format as enum ('pdf', 'epub', 'mobi', 'docx');

create table book_files (
  id uuid primary key default gen_random_uuid(),
  book_id uuid not null references books (id) on delete cascade,
  format book_file_format not null,
  storage_path text not null,     -- generated by the server; never the uploader's filename
  original_name text not null,    -- display only
  size_bytes bigint not null,
  detected jsonb not null default '{}'::jsonb, -- what the analyser actually found (title, author, pages, source, notes)
  created_at timestamptz not null default now(),
  unique (book_id, format)
);

create index book_files_book_idx on book_files (book_id);

alter table book_files enable row level security;
create policy book_files_staff_all on book_files for all using (is_staff()) with check (is_staff());
